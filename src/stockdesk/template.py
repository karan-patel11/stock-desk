"""stockdesk template: write the Switch template for this machine.

  stockdesk template [--out PATH] [--bridge slack|mattermost] [--ticker TICKER] [--mention-test]

Builds the desk-team template from the bundled skeleton and agent instructions, or writes the two-agent mention
test with --mention-test. Every tool call in the instructions becomes

    STOCKDESK_HOME=<home> <absolute path of stockdesk> <tool> ...

resolved now, on this machine: Switch Console may start Claude Code sessions without your shell PATH, and the Switch
template language has no field for a command path or per-agent environment variables (docs/TEMPLATES.md, The agent
block). Regenerate after reinstalling Stock Desk or moving its home.
"""
from __future__ import annotations

import argparse
import re
import shlex
import sys
from pathlib import Path
from typing import Sequence

from . import __version__, common, locate

MARKER = re.compile(r"^(?P<indent>[ ]*)@@INSTRUCTIONS:(?P<name>[a-z]+)@@[ ]*$")
AGENT_NAMES = ("chief", "fundamental", "technical", "sentiment")
MAX_LINES = {"chief": 80, "fundamental": 60, "technical": 60, "sentiment": 60}
DESK_AGENTS = ["desk-chief", "desk-fundamental", "desk-technical", "desk-sentiment"]
MENTION_AGENTS = ["s0-chief", "s0-technical"]
BRIDGE_DESCRIPTIONS = {
    "slack": "Pick your Slack connection (the Name you gave it in Switch). Mattermost only as the fallback.",
    "mattermost": "Pick your Mattermost connection (the Name you gave it in Switch).",
}
MENTION_BRIDGE_LINE = f'    description: "{BRIDGE_DESCRIPTIONS["slack"]}"'
UNVERIFIED = (
    "upper-case ticker in the room name desk-{ticker} (TEMPLATES.md says only 'name: text')",
    "whether the kickoff starts a new thread or posts at the channel top level",
)
# From docs/TEMPLATES.md, "Params" -> "Configuration model".
PARAM_TYPES = {"string", "number", "boolean", "enum", "agent", "bridge", "room", "user",
               "provider", "location", "machine", "directory"}
PARAM_KEYS = {"type", "description", "label", "default", "required", "input", "enum", "multiline",
              "pattern", "min", "max"}
BUILTINS = {"{$agents_dir}", "{$creator}"}

SWITCH_TEMPLATES_DOC = "https://github.com/sandbox-quantum/switch/blob/main/docs/TEMPLATES.md"
SWITCH_DOCS = "https://docs.switchagents.ai/flintai/switch"
BRIDGE_DOCS = {"slack": f"{SWITCH_DOCS}/deploy/messaging-apps/slack",
               "mattermost": f"{SWITCH_DOCS}/deploy/messaging-apps/mattermost"}


class TemplateError(Exception):
    pass


class _Parser(argparse.ArgumentParser):
    def error(self, message: str):  # type: ignore[override]
        raise TemplateError(message)


# --------------------------------------------------------------------------
# Building
# --------------------------------------------------------------------------

def tool_prefix(exe: list[str], home: Path) -> str:
    """What `$STOCKDESK` becomes: STOCKDESK_HOME=<home> <exe...>, shell-quoted."""
    return f"STOCKDESK_HOME={shlex.quote(str(home))} {locate.command_text(exe)}"


def _check_path(label: str, text: str) -> None:
    if not Path(text).is_absolute():
        raise TemplateError(f"{label} must be an absolute path, got {text!r}")
    if any(c in text for c in "{}\n\r\t"):
        raise TemplateError(f"{label} {text!r} contains a brace or control character; Switch would misread it")


def agent_text(name: str, exe: list[str], home: Path) -> str:
    resource = common.bundled("agents", f"{name}.md")
    if not resource.is_file():
        raise TemplateError(f"missing bundled agent file agents/{name}.md")
    text = resource.read_text(encoding="utf-8")
    lines = text.rstrip("\n").splitlines()
    if len(lines) > MAX_LINES[name]:
        raise TemplateError(f"agents/{name}.md has {len(lines)} lines; the limit is {MAX_LINES[name]}")
    if "\t" in text:
        raise TemplateError(f"agents/{name}.md contains a tab character")
    for number, line in enumerate(lines, 1):
        if "{" in line or "}" in line:
            raise TemplateError(f"agents/{name}.md:{number} contains a curly brace; Switch would treat it as a placeholder")
    text = text.replace("$STOCKDESK_HOME", shlex.quote(str(home)))
    text = re.sub(r"\$STOCKDESK\b", lambda _: tool_prefix(exe, home), text)
    leftover = re.search(r"\$[A-Z_]{3,}", text)
    if leftover:
        raise TemplateError(f"agents/{name}.md uses an unknown variable {leftover.group(0)}")
    return text.rstrip("\n")


def build_desk(exe: list[str], home: Path, bridge: str, ticker: str | None) -> str:
    for part in exe:
        if part != "-m" and part != "stockdesk":
            _check_path("stockdesk executable", part)
    _check_path("STOCKDESK_HOME", str(home))
    generated = (f"# Generated by stockdesk {__version__} for STOCKDESK_HOME={home} and the command "
                 f"{locate.command_text(exe)}. Regenerate after reinstalling or moving the home.")
    out: list[str] = []
    seen: list[str] = []
    for line in common.bundled("templates", "desk-team.skeleton").read_text(encoding="utf-8").splitlines():
        if line == "@@GENERATED@@":
            out.append(generated)
            continue
        if line == "@@TICKER_DEFAULT@@":
            if ticker:
                out.append(f'    default: "{ticker}"')
            continue
        line = line.replace("@@BRIDGE_DESCRIPTION@@", BRIDGE_DESCRIPTIONS[bridge])
        match = MARKER.match(line)
        if not match:
            out.append(line)
            continue
        name = match.group("name")
        seen.append(name)
        pad = match.group("indent")
        out.extend((pad + body) if body else "" for body in agent_text(name, exe, home).splitlines())
    if sorted(seen) != sorted(AGENT_NAMES):
        raise TemplateError(f"skeleton must inject exactly {sorted(AGENT_NAMES)}, found {sorted(seen)}")
    return "\n".join(out) + "\n"


def build_mention_test(bridge: str) -> str:
    text = common.bundled("templates", "mention-test.template.yaml").read_text(encoding="utf-8")
    if MENTION_BRIDGE_LINE not in text:
        raise TemplateError("mention-test template: bridge description line not found")
    return text.replace(MENTION_BRIDGE_LINE, f'    description: "{BRIDGE_DESCRIPTIONS[bridge]}"')


# --------------------------------------------------------------------------
# Validation (PyYAML is optional)
# --------------------------------------------------------------------------

def validate(text: str, agents: list[str], kickoff_prefix: str) -> str | None:
    """None when PyYAML is not installed. Raises TemplateError on a broken document."""
    try:
        import yaml
    except ImportError:
        return None
    try:
        doc = yaml.safe_load(text)
        params = doc["params"]
        if not isinstance(params, dict):
            raise TemplateError("params must be a mapping keyed by param name (TEMPLATES.md)")
        for key, spec in params.items():
            if not re.fullmatch(r"[a-z_][a-z0-9_]*", key):
                raise TemplateError(f"param name {key!r} is not a plain identifier")
            if not set(spec) <= PARAM_KEYS:
                raise TemplateError(f"param {key}: unknown keys {sorted(set(spec) - PARAM_KEYS)}")
            if spec.get("type", "string") not in PARAM_TYPES:
                raise TemplateError(f"param {key}: unknown type {spec.get('type')!r}")
        placeholders = set(re.findall(r"\{[^}]*\}", text)) - BUILTINS
        used = {p[1:-1] for p in placeholders}
        if used != set(params):
            raise TemplateError(f"declared params {sorted(params)} vs used placeholders {sorted(placeholders)}")
        names = [a["name"] for a in doc["agents"]]
        if names != agents or doc["room"]["agents"] != agents:
            raise TemplateError(f"agents {names} / room agents {doc['room']['agents']}, expected {agents}")
        for alias in (doc["room"].get("aliases") or {}).values():  # Switch: letters, digits, '.', '-', '_' only
            if not re.fullmatch(r"[A-Za-z0-9._-]+", alias):
                raise TemplateError(f"invalid alias {alias!r}")
        if not doc["kickoff"].strip().startswith(kickoff_prefix):
            raise TemplateError(f"kickoff must start with {kickoff_prefix!r}")
        for agent in doc["agents"]:
            if not agent["instructions"].strip() or not agent["directory"].endswith(agent["name"]):
                raise TemplateError(f"agent {agent['name']}: empty instructions or wrong directory")
            for field in ("provider", "location", "directory"):  # TEMPLATES.md: required for every agent
                if not agent.get(field):
                    raise TemplateError(f"agent {agent['name']} has no {field}")
    except (KeyError, TypeError, AttributeError, yaml.YAMLError) as exc:
        raise TemplateError(f"generated YAML is not a valid Switch template: {type(exc).__name__}: {exc}") from exc
    return f"YAML parsed: {len(agents)} agents, room {doc['room']['name']!r}"


# --------------------------------------------------------------------------
# What to do next, from the Switch docs
# --------------------------------------------------------------------------

def next_steps(out: Path, bridge: str, mention_test: bool) -> list[str]:
    app = bridge.capitalize()
    steps = [f"Next steps (from the Switch docs; anything they do not document is marked NOT DOCUMENTED):"]
    if bridge == "slack":
        steps += [
            "1. Connect Slack to your Switch server, once. Switch Console: Connect a messaging app -> Use your own app",
            "   instead -> Slack. By hand: select the server in the sidebar switcher, open its Home page, Messaging apps ->",
            "   Connect -> Slack; name the connection after the workspace; paste the Bot Token (xoxb-), App Token",
            "   (xapp-) and Workspace Id (T...); leave 'Allow creating channels from Switch' on; Connect; then link",
            "   your Slack account (This is me). Agents answer only accounts they recognise.",
            f"   {BRIDGE_DOCS['slack']}",
        ]
    else:
        steps += [f"1. Connect Mattermost to your Switch server, once, following {BRIDGE_DOCS['mattermost']}"]
    steps += [
        f"2. In Switch Console, open the Templates page and use {out}.",
        "   The docs say Switch Console reads a template on the Templates page and builds one form from its params;",
        "   NOT DOCUMENTED: the click path for loading a file of your own. If the page offers to paste a document,",
        "   paste the file's contents.",
        f"   {SWITCH_TEMPLATES_DOC}",
        f"3. On the form, pick your {app} connection (by the Name you gave it) under Messaging app"
        + ("" if mention_test else " and enter the Ticker") + ", then Create.",
        "   A refused run names every problem and its reason code (for example name_taken, provider_not_installed,",
        "   provider_login_missing); nothing is created. name_taken means these agents already exist on the server.",
    ]
    if mention_test:
        steps.append(f"4. Open the new channel in {app}. The kickoff asks s0-chief to test the mention; expect "
                     "s0-technical's PONG and MENTION TEST PASSED in one thread.")
    else:
        steps.append(f"4. Open the new channel in {app}. The kickoff posts '@desk-chief analyze <ticker>'; desk-chief asks "
                     "your goal. Spell agent names exactly: a misspelled name looks like silence.")
    return steps


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------

def _parser() -> argparse.ArgumentParser:
    parser = _Parser(prog="stockdesk template", description="Write the Switch template for this machine.")
    parser.add_argument("--out", help="output file (default ./desk-team.template.yaml, "
                                      "or ./mention-test.template.yaml with --mention-test)")
    parser.add_argument("--bridge", choices=sorted(BRIDGE_DESCRIPTIONS), default="slack",
                        help="messaging app the form's Messaging app input describes (default slack)")
    parser.add_argument("--ticker", help="prefill the form's Ticker input")
    parser.add_argument("--mention-test", action="store_true", help="the two-agent mention test instead of the desk")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    try:
        args = _parser().parse_args(list(sys.argv[1:] if argv is None else argv))
        if args.mention_test and args.ticker:
            raise TemplateError("--ticker does not apply to --mention-test")
        default_name = "mention-test.template.yaml" if args.mention_test else "desk-team.template.yaml"
        out = Path(args.out or default_name).expanduser().absolute()
        exe, how = locate.executable()
        try:
            home = common.home()
        except common.ToolError as exc:
            raise TemplateError(exc.detail) from exc
        if args.mention_test:
            text = build_mention_test(args.bridge)
            note = validate(text, MENTION_AGENTS, "@s0-chief")
        else:
            ticker = common.normalize_ticker(args.ticker) if args.ticker else None
            text = build_desk(exe, home, args.bridge, ticker)
            note = validate(text, DESK_AGENTS, "@desk-chief analyze")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
    except SystemExit as exc:  # --help
        return int(exc.code or 0)
    except (TemplateError, common.ToolError) as exc:
        print(f"error: {exc.detail if isinstance(exc, common.ToolError) else exc}", file=sys.stderr)
        return 1
    print(f"wrote {out}")
    if not args.mention_test:
        print(f"  agents call: {tool_prefix(exe, home)} <tool> ...  (stockdesk found: {how})")
        if len(exe) > 1:
            print("WARN: no stockdesk executable found; the template calls Python directly. Install with pipx for a "
                  "stable path.")
        if not home.is_dir():
            print(f"WARN: {home} does not exist yet; run `stockdesk init` before the first analysis.")
    print(f"  {note}" if note else "WARN: PyYAML not installed, YAML not validated")
    print("UNVERIFIED against Switch (confirm in Console):")
    for item in UNVERIFIED if not args.mention_test else UNVERIFIED[1:]:
        print(f"  - {item}")
    print()
    for line in next_steps(out, args.bridge, args.mention_test):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())

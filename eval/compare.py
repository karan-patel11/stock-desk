#!/usr/bin/env python3
"""compare.py [--before eval/results/before] [--after eval/results/after] [--out eval/results/before_after.md]

Side-by-side tables of the Phase 1 (runs.csv) and Phase 2 (injection.csv) results before and after a verify.py fix.
Reads only the two result folders; every number comes from their CSV files.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from inject import BENIGN, EXPECTED, FAULTS  # noqa: E402

ORDER = FAULTS[:3] + ("wrong_id", "wrong_id_similar") + FAULTS[4:] + BENIGN
RUN_FIELDS = [("m4_passed", "M4 passed"), ("m4_checked", "M4 checked"), ("m5_numbers_final", "M5 numbers"),
              ("m5_uncited_final", "M5 uncited"), ("m5_numbers_median_final", "M5 median/report"),
              ("m6_advice_fails", "M6 ADVICE fails"), ("m7_match", "M7 match")]


def load(path: Path) -> list[dict[str, str]]:
    with open(path, encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def as_expected(rows: list[dict[str, str]], kind: str) -> str:
    mine = [r for r in rows if r["type"] == kind and r["expected"] != "n/a"]
    return f"{sum(r['actual'] == r['expected'] for r in mine)}/{len(mine)}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--before", type=Path, default=HERE / "results" / "before")
    parser.add_argument("--after", type=Path, default=HERE / "results" / "after")
    parser.add_argument("--out", type=Path, default=HERE / "results" / "before_after.md")
    args = parser.parse_args(argv)
    inj_b, inj_a = load(args.before / "injection.csv"), load(args.after / "injection.csv")
    runs_b = {r["run"]: r for r in load(args.before / "runs.csv")}
    runs_a = {r["run"]: r for r in load(args.after / "runs.csv")}

    lines = ["# Before and after the verify.py URL fix", "",
             "Generated by `eval/compare.py` from `eval/results/before/` (verify.py before commit 8e62c76) and "
             "`eval/results/after/`. Same corpus, same seed (7).", "",
             "## Phase 2: verify result as expected, per type", "",
             "| Type | Expected | Before | After |", "|---|---|---|---|"]
    for kind in ORDER:
        lines.append(f"| {kind} | {EXPECTED[kind]} | {as_expected(inj_b, kind)} | {as_expected(inj_a, kind)} |")
    benign_b = [r for r in inj_b if r["type"] in BENIGN and r["expected"] != "n/a"]
    benign_a = [r for r in inj_a if r["type"] in BENIGN and r["expected"] != "n/a"]
    lines += ["", f"False alarms (clean + legit_round): before {sum(r['actual'] == 'FAIL' for r in benign_b)}/"
              f"{len(benign_b)}, after {sum(r['actual'] == 'FAIL' for r in benign_a)}/{len(benign_a)}.", ""]
    after = {r["variant"]: r for r in inj_a}
    changed = [(b, after[b["variant"]]) for b in inj_b
               if b["variant"] in after and b["actual"] != after[b["variant"]]["actual"]]
    missing = sorted({r["variant"] for r in inj_b} ^ set(after))
    lines += [f"Variants whose result changed: {len(changed)}/{len(inj_b)}"
              + (f"; variants present in only one run: {', '.join(missing)}" if missing else "") + ".", ""]
    lines += [f"- `{b['variant']}`: {b['actual']} → {a['actual']} (before: {b['detail']})" for b, a in changed]

    lines += ["", "## Phase 1: pre-eval runs", "", "| Run | " + " | ".join(f"{label} before | after" for _, label in RUN_FIELDS) + " |",
              "|---|" + "---|---|" * len(RUN_FIELDS)]
    for run in sorted(r for r, row in runs_b.items() if row["set"] == "pre-eval"):
        b, a = runs_b[run], runs_a.get(run, {})
        cells = []
        for field, _ in RUN_FIELDS:
            cells += [b.get(field, "") or "–", a.get(field, "") or "–"]
        lines.append(f"| {run} {b['ticker']} | " + " | ".join(cells) + " |")
    diffs = [(run, f, runs_b[run][f], runs_a.get(run, {}).get(f)) for run in runs_b for f in runs_b[run]
             if f not in ("notes", "root") and runs_b[run][f] != runs_a.get(run, {}).get(f)]
    lines += ["", f"runs.csv cells that changed (all 36 runs, notes excluded): {len(diffs)}", ""]
    lines += [f"- {run} {field}: {old!r} → {new!r}" for run, field, old, new in diffs]
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"-> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

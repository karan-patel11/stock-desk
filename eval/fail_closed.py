#!/usr/bin/env python3
"""fail_closed.py [--out eval/results/after]

M9 (eval/METRICS.md): runs tests/test_fail_closed.py offline with pytest --junitxml, parses the XML (stdlib
xml.etree) and writes <out>/fail_closed.md. The XML goes to a temp folder and is deleted: pytest records the
machine's hostname in it.

The tests assert CURRENT behaviour (decided 24 Nov 2026), so a passing case means "behaves as documented below", not
"behaves as the Phase 3 spec said". The spec column and the "fails closed" judgment are written down here, next to the
test names they describe, and are only reported when the case's tests pass.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
TEST_FILE = REPO / "tests" / "test_fail_closed.py"

CASES = {
    1: ("Bank (JPM-style revenue tag)",
        "revenue no_data; net income and EPS still reported; confidence lowered per the rule",
        "JPM-style (stale legacy Revenues tag): as spec. A bank with no legacy revenue tag: no_data for the whole tool, "
        "so net income and EPS are lost. Confidence drops only if the chief passes fund=no_data (then -1 and capped)",
        "yes", "no"),
    2: ("Unknown ticker",
        "bad_input, exit 1",
        "Well-formed but unknown: no_data ('not in the SEC ticker map'), exit 1; malformed: bad_input, exit 1. "
        "round start accepts any well-formed ticker; confidence.py then refuses the empty run (no_data)",
        "yes", "no"),
    3: ("GDELT HTTP 429",
        "rate_limited; sentiment cannot raise any horizon's confidence",
        "rate_limited, one request, no news entries; over 1,296 input combinations no sentiment value scores above "
        "neutral, and no_data scores below any medium or high",
        "yes", "yes"),
    4: ("Stale EPS (past 200 days)",
        "reported as stale or no_data, never as current",
        "listed as stale, absent from every quarter, never filled from an annual value; other metrics kept",
        "yes", "yes"),
    5: ("Foreign filer (20-F, no 10-Q)",
        "fail closed with a clear detail",
        "fails closed (no_data), but the detail is 'no quarterly revenue found' with no mention of 20-F or a foreign "
        "filer. An IFRS-only filer gets 'foreign filer or no XBRL'",
        "yes", "no"),
    6: ("Partial bar during market hours (known limitation)",
        "document the observed behaviour; don't fix",
        "a bar dated today and fetched mid-session is reported as last_close; nothing marks it as partial",
        "no", "documented"),
}


def run_pytest(xml_path: Path) -> int:
    cmd = [sys.executable, "-m", "pytest", str(TEST_FILE), "-q", "-p", "no:cacheprovider", f"--junitxml={xml_path}"]
    return subprocess.run(cmd, cwd=REPO, capture_output=True, text=True).returncode


def parse(xml_path: Path) -> dict[int, list[tuple[str, bool]]]:
    by_case: dict[int, list[tuple[str, bool]]] = {n: [] for n in CASES}
    for case in ET.parse(xml_path).getroot().iter("testcase"):
        name = case.get("name", "")
        if not name.startswith("test_fc"):
            continue
        number = int(name[len("test_fc"):].split("_")[0])
        failed = any(child.tag in ("failure", "error", "skipped") for child in case)
        by_case.setdefault(number, []).append((name, not failed))
    return by_case


def report(by_case: dict[int, list[tuple[str, bool]]]) -> str:
    lines = ["# Fail-closed cases (M9)", "",
             "Generated by `eval/fail_closed.py` from `tests/test_fail_closed.py` (offline). Tests assert current "
             "behaviour; a case 'holds' when all its tests pass.", "",
             "| Case | Expected by spec | Actual | Fails closed | Matches spec | Tests |", "|---|---|---|---|---|---|"]
    holds = {}
    for number, (title, spec, actual, closed, matches) in CASES.items():
        tests = by_case.get(number, [])
        passed = sum(ok for _, ok in tests)
        holds[number] = bool(tests) and passed == len(tests)
        shown_actual = actual if holds[number] else f"TESTS FAIL: behaviour changed from: {actual}"
        lines.append(f"| {number}. {title} | {spec} | {shown_actual} | {closed if holds[number] else '?'} | "
                     f"{matches if holds[number] else '?'} | {passed}/{len(tests)} |")
    scored = [n for n in CASES if CASES[n][4] != "documented"]
    hold = [n for n in scored if holds[n]]
    closed = [n for n in hold if CASES[n][3] == "yes"]
    spec = [n for n in hold if CASES[n][4] == "yes"]
    total_tests = sum(len(t) for t in by_case.values())
    passed_tests = sum(ok for t in by_case.values() for _, ok in t)
    lines += ["",
              f"- **Cases behaving as documented:** {len(hold)}/{len(scored)} (case 6 documented separately: "
              f"{'holds' if holds[6] else 'CHANGED'})",
              f"- **Cases that fail closed:** {len(closed)}/{len(scored)}",
              f"- **Cases matching the Phase 3 spec exactly:** {len(spec)}/{len(scored)} (cases {', '.join(map(str, spec))})",
              f"- **Tests:** {passed_tests}/{total_tests} passed", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=HERE / "results" / "after")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        xml_path = Path(tmp) / "fail_closed.xml"
        run_pytest(xml_path)
        text = report(parse(xml_path))
    (args.out / "fail_closed.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
